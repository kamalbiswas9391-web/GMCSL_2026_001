import type { MemberRecord, ReceiptRecord, SocietySettings } from '../types';

function hexToRgb(hex: string, fallback: [number, number, number]): [number, number, number] {
  const clean = String(hex || '').replace('#', '');
  if (/^[0-9a-fA-F]{6}$/.test(clean)) {
    return [
      parseInt(clean.slice(0, 2), 16),
      parseInt(clean.slice(2, 4), 16),
      parseInt(clean.slice(4, 6), 16),
    ];
  }
  return fallback;
}

export async function generateQrDataUrl(text: string): Promise<string> {
  return QRCode.toDataURL(text, { margin: 1, width: 160, color: { dark: '#142D4E', light: '#FFFFFF' } });
}

export async function downloadReceiptPdf(receipt: ReceiptRecord, settings: SocietySettings) {
  const doc = new jsPDF();
  const isProvisional = receipt.verificationStatus !== 'Verified';

  // Header band
  doc.setFillColor(8, 116, 67);
  doc.rect(0, 0, 210, 32, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(15);
  doc.setFont('helvetica', 'bold');
  doc.text(settings.societyName || 'Garakhia Dhap Multipurpose Co-operative Society Ltd.', 14, 14);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(`${settings.address || 'Garakhia Dhap, Assam'}  |  ${settings.contactPhone || ''}  |  ${settings.officialEmail || ''}`, 14, 22);
  if (settings.registrationDetails) {
    doc.text(`Reg: ${settings.registrationDetails}`, 14, 27);
  }

  // Receipt Title & Status
  doc.setTextColor(20, 45, 78);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(`${receipt.receiptType.toUpperCase()} RECEIPT`, 14, 44);

  if (isProvisional) {
    doc.setFillColor(254, 243, 199);
    doc.rect(14, 48, 182, 10, 'F');
    doc.setTextColor(180, 83, 9);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.text('STATUS: PROVISIONAL / NOT YET VERIFIED (Saved Offline or Pending Online Verification)', 18, 54.5);
  } else {
    doc.setFillColor(220, 252, 231);
    doc.rect(14, 48, 182, 10, 'F');
    doc.setTextColor(22, 101, 52);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.text('STATUS: OFFICIAL VERIFIED RECEIPT', 18, 54.5);
  }

  autoTable(doc, {
    startY: 64,
    theme: 'grid',
    headStyles: { fillColor: [20, 45, 78] },
    styles: { fontSize: 10, cellPadding: 4 },
    head: [['Field', 'Details']],
    body: [
      ['Receipt Number', receipt.receiptNumber],
      ['Date', receipt.date],
      ['Member ID', receipt.memberId],
      ['Member Name', receipt.memberName],
      ['Transaction Category', receipt.receiptType],
      ['Payment Method', receipt.paymentMethod],
      ['Amount', `${settings.currencySymbol || 'Rs.'} ${Number(receipt.amount).toFixed(2)}`],
      ['Transaction Details', receipt.details || '-'],
      ['Verification Status', receipt.verificationStatus],
      ['Authorized / Recorded By', receipt.authorizedBy],
    ],
  });

  const finalY = (doc as any).lastAutoTable?.finalY || 160;
  const qr = await generateQrDataUrl(`GMCSL-REC:${receipt.receiptNumber}|MEM:${receipt.memberId}|AMT:${receipt.amount}|STATUS:${receipt.verificationStatus}`);
  doc.addImage(qr, 'PNG', 14, finalY + 10, 28, 28);

  doc.setTextColor(29, 41, 57);
  doc.setFontSize(9);
  doc.text('Authorized Signature', 150, finalY + 34);
  doc.line(140, finalY + 29, 194, finalY + 29);

  doc.setFontSize(8);
  doc.setTextColor(102, 112, 133);
  doc.text('Generated by GMCSL Society Management System. Verify receipt QR for authenticity.', 14, finalY + 46);

  doc.save(`${receipt.receiptNumber}.pdf`);
}

export async function downloadMemberIdCardPdf(member: MemberRecord, settings: SocietySettings) {
  const tpl = resolveCredentialTemplate('id', settings);
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: [86, 54] });

  const bgRgb = hexToRgb(tpl.backgroundColor, [255, 255, 255]);
  const priRgb = hexToRgb(tpl.primaryColor, [8, 116, 67]);
  const secRgb = hexToRgb(tpl.secondaryColor, [20, 45, 78]);
  const accRgb = hexToRgb(tpl.accentColor, [213, 166, 66]);

  doc.setFillColor(...bgRgb);
  doc.rect(0, 0, 86, 54, 'F');

  if (tpl.borderStyle !== 'none') {
    doc.setDrawColor(...priRgb);
    doc.setLineWidth(tpl.borderStyle === 'double' || tpl.borderStyle === 'ornate' ? 0.8 : 0.4);
    doc.rect(1.5, 1.5, 83, 51);
  }

  // Header band
  doc.setFillColor(...secRgb);
  doc.rect(0, 0, 86, 13.5, 'F');
  doc.setFillColor(...priRgb);
  doc.rect(0, 13.5, 86, 1.8, 'F');

  if (tpl.showLogo && settings.logoUrl && settings.logoUrl.startsWith('data:image')) {
    try {
      doc.addImage(settings.logoUrl, 'PNG', 3.5, 2.2, 8.5, 8.5);
    } catch {
      // ignore invalid logo image format
    }
  }

  const titleOffset = tpl.showLogo && settings.logoUrl?.startsWith('data:image') ? 14 : 4;
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'bold');
  doc.text(renderTemplateText(tpl.title || settings.shortName || 'GMCSL', member, settings).slice(0, 38), titleOffset, 5.8);
  doc.setFontSize(5.8);
  doc.setFont('helvetica', 'normal');
  doc.text(renderTemplateText(tpl.subtitle || settings.societyName, member, settings).slice(0, 48), titleOffset, 10.3);

  // Member photo
  if (tpl.showPhoto) {
    if (member.photoUrl && member.photoUrl.startsWith('data:image')) {
      try {
        doc.addImage(member.photoUrl, 'JPEG', 4, 18.5, 17, 21);
      } catch {
        doc.rect(4, 18.5, 17, 21);
      }
    } else {
      doc.setDrawColor(190);
      doc.rect(4, 18.5, 17, 21);
      doc.setTextColor(120, 120, 120);
      doc.setFontSize(5);
      doc.text('PHOTO', 9.5, 29.5);
    }
  }

  // Dynamic elements
  for (const el of tpl.elements.filter((e) => e.visible)) {
    const rgb = hexToRgb(el.color || tpl.textColor, [29, 41, 57]);
    doc.setTextColor(...rgb);
    doc.setFontSize(el.fontSize || 6.5);
    doc.setFont('helvetica', el.fontWeight === 'bold' ? 'bold' : 'normal');
    const txt = renderTemplateText(el.valueTemplate, member, settings);
    doc.text(txt, el.x, el.y, { align: el.align || 'left' });
  }

  if (tpl.showQr) {
    const qr = await generateQrDataUrl(`GMCSL-ID:${member.memberId}|${member.memberName}|${member.joinDate}`);
    doc.addImage(qr, 'PNG', 66, 18.5, 16, 16);
  }

  // Signatures & footer
  doc.setDrawColor(...accRgb);
  doc.setTextColor(...hexToRgb(tpl.textColor, [29, 41, 57]));
  doc.setFontSize(5);
  if (tpl.showSecretarySignature) {
    doc.line(58, 45.5, 82, 45.5);
    doc.text('Secretary Signature', 70, 48.5, { align: 'center' });
  } else if (tpl.showPresidentSignature) {
    doc.line(58, 45.5, 82, 45.5);
    doc.text('President Signature', 70, 48.5, { align: 'center' });
  } else if (tpl.showCustomSignature) {
    if (tpl.customSignatureUrl && tpl.customSignatureUrl.startsWith('data:image')) {
      try {
        doc.addImage(tpl.customSignatureUrl, 'PNG', 62, 37.5, 16, 7.5);
      } catch {
        // fallback line
      }
    }
    doc.line(58, 45.5, 82, 45.5);
    doc.text(tpl.customSignatureLabel || 'Authorized Sign', 70, 48.5, { align: 'center' });
  }

  if (tpl.footerText) {
    doc.setFontSize(4.5);
    doc.setTextColor(102, 112, 133);
    doc.text(renderTemplateText(tpl.footerText, member, settings).slice(0, 62), 4, 51);
  }

  doc.save(`${member.memberId}_ID_Card.pdf`);
}

export async function downloadMembershipCertificatePdf(
  member: MemberRecord,
  certNumber: string,
  settings: SocietySettings
) {
  const tpl = resolveCredentialTemplate('cert', settings);
  const doc = new jsPDF({ orientation: 'landscape' });

  const bgRgb = hexToRgb(tpl.backgroundColor, [255, 255, 255]);
  const priRgb = hexToRgb(tpl.primaryColor, [8, 116, 67]);
  const secRgb = hexToRgb(tpl.secondaryColor, [20, 45, 78]);
  const accRgb = hexToRgb(tpl.accentColor, [213, 166, 66]);

  doc.setFillColor(...bgRgb);
  doc.rect(0, 0, 297, 210, 'F');

  if (tpl.borderStyle === 'ornate') {
    doc.setDrawColor(...priRgb);
    doc.setLineWidth(2);
    doc.rect(10, 10, 277, 190);
    doc.setDrawColor(...accRgb);
    doc.setLineWidth(0.8);
    doc.rect(14, 14, 269, 182);
  } else if (tpl.borderStyle === 'double') {
    doc.setDrawColor(...priRgb);
    doc.setLineWidth(1.5);
    doc.rect(10, 10, 277, 190);
    doc.setLineWidth(0.6);
    doc.rect(13, 13, 271, 184);
  } else if (tpl.borderStyle === 'solid') {
    doc.setDrawColor(...priRgb);
    doc.setLineWidth(1.5);
    doc.rect(11, 11, 275, 188);
  }

  if (tpl.showLogo && settings.logoUrl && settings.logoUrl.startsWith('data:image')) {
    try {
      doc.addImage(settings.logoUrl, 'PNG', 22, 20, 18, 18);
    } catch {
      // ignore invalid image
    }
  }

  doc.setTextColor(...secRgb);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(renderTemplateText(tpl.subtitle || settings.societyName, member, settings, certNumber), 148.5, 34, { align: 'center' });

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(102, 112, 133);
  doc.text(`${settings.address || 'Garakhia Dhap, Assam'} ${settings.registrationDetails ? ' | Reg: ' + settings.registrationDetails : ''}`, 148.5, 42, { align: 'center' });

  doc.setFillColor(...priRgb);
  doc.rect(75, 50, 147, 12, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(renderTemplateText(tpl.title || 'CERTIFICATE OF MEMBERSHIP', member, settings, certNumber), 148.5, 58, { align: 'center' });

  doc.setTextColor(...hexToRgb(tpl.textColor, [29, 41, 57]));
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text(`Certificate No: ${certNumber}`, 24, 76);
  doc.text(`Issue Date: ${new Date().toISOString().slice(0, 10)}`, 273, 76, { align: 'right' });

  if (tpl.showPhoto && member.photoUrl && member.photoUrl.startsWith('data:image')) {
    try {
      doc.addImage(member.photoUrl, 'JPEG', 245, 84, 26, 32);
    } catch {
      // ignore invalid photo
    }
  }

  for (const el of tpl.elements.filter((e) => e.visible)) {
    const rgb = hexToRgb(el.color || tpl.textColor, [29, 41, 57]);
    doc.setTextColor(...rgb);
    doc.setFontSize(el.fontSize || 12);
    doc.setFont('helvetica', el.fontWeight === 'bold' ? 'bold' : 'normal');
    doc.text(renderTemplateText(el.valueTemplate, member, settings, certNumber), el.x, el.y, { align: el.align || 'center' });
  }

  if (tpl.showQr) {
    const qr = await generateQrDataUrl(`GMCSL-CERT:${certNumber}|MEM:${member.memberId}|${member.memberName}`);
    doc.addImage(qr, 'PNG', 26, 148, 28, 28);
  }

  doc.setFontSize(10);
  doc.setDrawColor(...secRgb);
  doc.setTextColor(...hexToRgb(tpl.textColor, [29, 41, 57]));

  const sigPositions: Array<{ label: string; imgUrl?: string; x: number }> = [];
  if (tpl.showSecretarySignature) sigPositions.push({ label: 'Secretary Signature', imgUrl: settings.secretarySignatureUrl, x: 118 });
  if (tpl.showPresidentSignature) sigPositions.push({ label: 'President Signature', imgUrl: settings.presidentSignatureUrl, x: 184 });
  if (tpl.showCustomSignature) sigPositions.push({ label: tpl.customSignatureLabel || 'Authorized Signature', imgUrl: tpl.customSignatureUrl, x: 242 });

  sigPositions.forEach((sig, i) => {
    const cx = sigPositions.length === 1 ? 225 : sigPositions.length === 2 ? (i === 0 ? 150 : 235) : sig.x;
    if (sig.imgUrl && sig.imgUrl.startsWith('data:image')) {
      try {
        doc.addImage(sig.imgUrl, 'PNG', cx - 18, 152, 36, 16);
      } catch {
        // ignore invalid sig
      }
    }
    doc.line(cx - 26, 172, cx + 26, 172);
    doc.text(sig.label, cx, 178, { align: 'center' });
  });

  if (tpl.footerText) {
    doc.setFontSize(8.5);
    doc.setTextColor(102, 112, 133);
    doc.text(renderTemplateText(tpl.footerText, member, settings, certNumber), 148.5, 190, { align: 'center' });
  }

  doc.save(`${member.memberId}_Membership_Certificate.pdf`);
}

export function exportTableToPdf(
  title: string,
  headers: string[],
  rows: Array<Array<string | number>>,
  settings: SocietySettings,
  fileName: string
) {
  const doc = new jsPDF({ orientation: headers.length > 6 ? 'landscape' : 'portrait' });
  doc.setFillColor(20, 45, 78);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 24, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text(settings.societyName || 'GMCSL Society Management System', 14, 11);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`${title}  |  Generated: ${new Date().toLocaleString()}`, 14, 18);

  autoTable(doc, {
    startY: 30,
    head: [headers],
    body: rows,
    styles: { fontSize: 8.5, cellPadding: 2.5 },
    headStyles: { fillColor: [8, 116, 67] },
  });

  doc.save(`${fileName}.pdf`);
}

export function exportTableToExcel(
  sheetName: string,
  headers: string[],
  rows: Array<Array<string | number>>,
  fileName: string
) {
  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.aoa_to_sheet([headers, ...rows]);
  XLSX.utils.book_append_sheet(wb, ws, sheetName.slice(0, 31));
  XLSX.writeFile(wb, `${fileName}.xlsx`);
}

export function exportTableToCsv(
  headers: string[],
  rows: Array<Array<string | number>>,
  fileName: string
) {
  const escape = (val: string | number) => {
    const s = String(val ?? '');
    if (s.includes(',') || s.includes('"') || s.includes('\n')) {
      return `"${s.replace(/"/g, '""')}"`;
    }
    return s;
  };
  const csv = [headers.map(escape).join(','), ...rows.map((r) => r.map(escape).join(','))].join('\n');
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${fileName}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}
